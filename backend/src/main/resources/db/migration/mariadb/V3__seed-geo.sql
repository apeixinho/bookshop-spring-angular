USE `catalog_db` ;

CREATE TABLE IF NOT EXISTS country (
  id INT NOT NULL,
  code VARCHAR(2) DEFAULT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS country_translation (
  id BIGINT NOT NULL AUTO_INCREMENT,
  country_id INT NOT NULL,
  locale VARCHAR(8) NOT NULL,
  name VARCHAR(255) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_country_locale (country_id, locale),
  CONSTRAINT fk_country_translation FOREIGN KEY (country_id) REFERENCES country (id)
);

CREATE TABLE IF NOT EXISTS state (
  id INT NOT NULL AUTO_INCREMENT,
  country_id INT NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_country FOREIGN KEY (country_id) REFERENCES country (id)
);

CREATE TABLE IF NOT EXISTS state_translation (
  id BIGINT NOT NULL AUTO_INCREMENT,
  state_id INT NOT NULL,
  locale VARCHAR(8) NOT NULL,
  name VARCHAR(255) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_state_locale (state_id, locale),
  CONSTRAINT fk_state_translation FOREIGN KEY (state_id) REFERENCES state (id)
);

